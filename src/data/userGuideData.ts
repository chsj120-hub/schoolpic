/**
 * 마크다운 문서로 변환하는 생성 함수
 */
export function generateUserGuideMarkdown(): string {
  let md = `# [스쿨픽 (SchoolPick)] 교사용 통합 운영 매뉴얼 & 사용자 가이드\n\n`;
  md += `> **문서 버전:** v1.0.4 | **최종 갱신:** 2026-10-25\n`;
  md += `> **발행처:** 스쿨픽 공식 개발팀 (SchoolPick Core Team)\n`;
  md += `> **지원 대상:** 전국 초·중·고등학교 교직원, 학생 및 학부모\n\n`;
  md += `---\n\n`;

  USER_GUIDE_SECTIONS.forEach((sec) => {
    md += `## ${sec.title}\n\n`;
    md += `**[개요]** ${sec.summary}\n\n`;
    sec.content.forEach((item) => {
      md += `- ${item}\n`;
    });
    md += `\n`;
    if (sec.tips && sec.tips.length > 0) {
      md += `> **💡 운영 꿀팁 & 주의사항:**\n`;
      sec.tips.forEach((tip) => {
        md += `> • ${tip}\n`;
      });
      md += `\n`;
    }
    md += `---\n\n`;
  });

  md += `### [법적 고지 및 저작권 명세]\n`;
  md += `- Copyright © 2026 SchoolPick Team. All Rights Reserved.\n`;
  md += `- 개인정보보호법 제15조 및 교육활동 보호 지침 준수.\n`;
  md += `- 기술 문의 및 기능 제안: chsj120@gmail.com\n`;

  return md;
}
